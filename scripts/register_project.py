"""Register a host project for native execution (run on the host, not in the container).

    .venv/bin/python scripts/register_project.py music-generation ~/Documents/research/MusicGeneration
    .venv/bin/python scripts/register_project.py volley-vision ~/src/VolleyVision --execution native

Adds the project to config/projects.yaml and its bind mount to compose.projects.yaml.
Registry edits apply without a restart; a new or changed mount needs
`docker compose up -d codepartner`. Only the given directory is mounted: `/`, a home
directory and their ancestors are refused.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "config" / "projects.yaml"
COMPOSE = ROOT / "compose.projects.yaml"
_ID = re.compile(r"^[a-z0-9][a-z0-9_.-]*$")


def _refused(path: Path) -> str | None:
    if not path.is_dir():
        return f"{path} is not an existing directory"
    home = Path.home().resolve()
    if path == Path("/") or path == home or path in home.parents:
        return f"refusing to mount {path}: mount a single project directory instead"
    return None


def _load(path: Path, default: dict) -> dict:
    if not path.exists():
        return default
    data = yaml.safe_load(path.read_text()) or {}
    if not isinstance(data, dict):
        raise SystemExit(f"{path} must contain a mapping")
    return data


def register(project_id: str, host_path: Path, execution: str, replace: bool) -> bool:
    """Write both files; return True when the container must be recreated."""
    workspace = f"/workspace/{project_id}"
    registry = _load(REGISTRY, {"projects": {}})
    projects = registry.setdefault("projects", {}) or {}
    registry["projects"] = projects
    existing = projects.get(project_id)
    if existing and existing.get("host_path") not in (None, str(host_path)) and not replace:
        raise SystemExit(f"{project_id!r} is already registered for {existing['host_path']}; "
                         "pass --replace to change it")
    projects[project_id] = {"workspace": workspace, "host_path": str(host_path),
                            "execution": execution}
    compose = _load(COMPOSE, {"services": {"codepartner": {"volumes": []}}})
    service = compose.setdefault("services", {}).setdefault("codepartner", {})
    volumes = service.setdefault("volumes", []) or []
    service["volumes"] = volumes
    mount = {"type": "bind", "source": str(host_path), "target": workspace,
             "bind": {"create_host_path": False}}
    current = next((item for item in volumes
                    if isinstance(item, dict) and item.get("target") == workspace), None)
    if current is not None and current.get("source") != str(host_path) and not replace:
        raise SystemExit(f"{workspace} is already mounted from {current.get('source')}; "
                         "pass --replace to change it")
    recreate = current != mount
    service["volumes"] = [item for item in volumes
                          if not (isinstance(item, dict) and item.get("target") == workspace)]
    service["volumes"].append(mount)
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY.write_text(yaml.safe_dump(registry, sort_keys=False))
    COMPOSE.write_text(
        "# Generated by scripts/register_project.py; chain it with\n"
        "# COMPOSE_FILE=compose.yaml:compose.projects.yaml in .env.\n"
        + yaml.safe_dump(compose, sort_keys=False))
    return recreate


def _compose_chained() -> bool:
    """Whether COMPOSE_FILE (environment or .env) already includes the project mounts."""
    if "compose.projects.yaml" in os.environ.get("COMPOSE_FILE", ""):
        return True
    env = ROOT / ".env"
    return env.exists() and any(
        line.strip().startswith("COMPOSE_FILE=") and "compose.projects.yaml" in line
        for line in env.read_text().splitlines())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("project_id")
    parser.add_argument("host_path")
    parser.add_argument("--execution", choices=("auto", "native", "ide"), default="native")
    parser.add_argument("--replace", action="store_true",
                        help="change the host path of an existing registration")
    args = parser.parse_args(argv)
    if not _ID.match(args.project_id):
        parser.error("project id must use lowercase letters, digits, '-', '_' or '.'")
    host_path = Path(os.path.expanduser(args.host_path)).resolve()
    if reason := _refused(host_path):
        parser.error(reason)
    recreate = register(args.project_id, host_path, args.execution, args.replace)
    print(f"Registered {args.project_id}: {host_path} -> /workspace/{args.project_id}")
    if subprocess.run(["git", "-C", str(host_path), "rev-parse", "--show-toplevel"],
                      capture_output=True, text=True).stdout.strip() != str(host_path):
        print("Note: this directory is not the root of a git repository; native execution "
              "needs git for change detection, so native tasks will fail.")
    if not _compose_chained():
        print("Add COMPOSE_FILE=compose.yaml:compose.projects.yaml to .env so Compose "
              "includes the project mounts.")
    if recreate:
        print("A new bind mount was added: recreate the container to apply it:\n"
              "  docker compose up -d codepartner")
    else:
        print("The mount already existed; no container recreation is needed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
