"""Generate observability/.env for compose.observability.yaml (run once, on the host).

    python scripts/observability_init.py
    python scripts/observability_init.py --port 3100 --email you@example.com

Writes random secrets for Langfuse's PostgreSQL, ClickHouse, Redis, MinIO and
NextAuth, a Langfuse project key pair (created on first start by Langfuse's headless
initialization), the first user's login, and LANGFUSE_OTLP_AUTH: the base64 Basic
credential the OpenTelemetry Collector sends to Langfuse. The collector cannot
base64-encode in its configuration, and the basicauth extension is contrib-only.

Never overwrites an existing file. Code Partner itself needs none of these values.
"""

from __future__ import annotations

import argparse
import base64
import os
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "observability" / ".env"


def render(port: int, email: str) -> tuple[str, str]:
    public_key = "pk-lf-" + secrets.token_hex(16)
    secret_key = "sk-lf-" + secrets.token_hex(16)
    password = secrets.token_urlsafe(18)
    auth = base64.b64encode(f"{public_key}:{secret_key}".encode()).decode()
    values = {
        "LANGFUSE_PORT": str(port),
        "NEXTAUTH_URL": f"http://localhost:{port}",
        "NEXTAUTH_SECRET": secrets.token_hex(32),
        "SALT": secrets.token_hex(32),
        "ENCRYPTION_KEY": secrets.token_hex(32),
        "POSTGRES_PASSWORD": secrets.token_hex(24),
        "CLICKHOUSE_PASSWORD": secrets.token_hex(24),
        "REDIS_AUTH": secrets.token_hex(24),
        "MINIO_ROOT_PASSWORD": secrets.token_hex(24),
        "LANGFUSE_INIT_ORG_ID": "codepartner",
        "LANGFUSE_INIT_ORG_NAME": "Code Partner",
        "LANGFUSE_INIT_PROJECT_ID": "codepartner",
        "LANGFUSE_INIT_PROJECT_NAME": "Code Partner",
        "LANGFUSE_INIT_USER_EMAIL": email,
        "LANGFUSE_INIT_USER_NAME": "Code Partner Admin",
        "LANGFUSE_INIT_USER_PASSWORD": password,
        "LANGFUSE_PUBLIC_KEY": public_key,
        "LANGFUSE_SECRET_KEY": secret_key,
        "LANGFUSE_BASE_URL": f"http://localhost:{port}",
        "LANGFUSE_OTLP_ENDPOINT": "http://langfuse-web:3000/api/public/otel/v1/traces",
        "LANGFUSE_OTLP_AUTH": auth,
    }
    header = ("# Generated by scripts/observability_init.py. Secrets: never commit.\n"
              "# Used only by compose.observability.yaml and scripts/smoke_observability.py.\n")
    # Quote values with spaces so the file is valid for both Compose and a POSIX shell.
    lines = "".join(f'{key}="{value}"\n' if " " in value else f"{key}={value}\n"
                    for key, value in values.items())
    return header + lines, password


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--port", type=int, default=3000, help="local Langfuse web port")
    parser.add_argument("--email", default="admin@codepartner.local",
                        help="first Langfuse user (login only; no mail is sent)")
    args = parser.parse_args()
    if TARGET.exists():
        print(f"{TARGET} already exists; not overwriting.", file=sys.stderr)
        return 1
    text, password = render(args.port, args.email)
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(TARGET, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as handle:
        handle.write(text)
    print(f"Wrote {TARGET} (mode 600).")
    print(f"Langfuse login: {args.email} / {password}  (also stored in that file)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
